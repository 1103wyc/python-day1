# task3.py —— 一周跑步记录（批改后的可运行版本）
# 和你原来的差别只有三类：①判断对象 ②变量用途 ③两个 if 是并排的，不是嵌套的
# 运行：python task3.py

km = [5.2, 3.0, 0, 8.4, 2.5, 6.0, 4.8]    # 一周 7 天，每天跑了几公里

total = sum(km)
avg = total / len(km)

最多 = km[0]        # 擂主：先让第 1 天上台
第几天 = 1          # 擂主是第几天
休息天数 = 0        # 计数器：0 公里的日子

for i in range(len(km)):
    if km[i] > 最多:              # 比的是"那天的公里数"，不是编号 i
        最多 = km[i]
        第几天 = i + 1
    if km[i] == 0:                # 和上面那件事无关，所以是并排的 if，不是嵌在里面
        休息天数 += 1

print(f"总公里数：{total:.1f}")
print(f"平均每天：{avg:.1f}")
print(f"跑得最多：第 {第几天} 天 {最多} 公里")
print(f"0 公里的日子：{休息天数} 天")
