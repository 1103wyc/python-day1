# demo4.py —— 把 task3 的循环"打开来看"
# 每一圈结束时，把 4 个变量当时的值打印出来，你就能看见循环在干嘛
# 运行：python demo4.py

km = [5.2, 3.0, 0, 8.4, 2.5, 6.0, 4.8]

最多 = km[0]
第几天 = 1
休息天数 = 0
print(f"进循环之前：最多={最多} 第几天={第几天} 休息天数={休息天数}")
print()

for i in range(len(km)):
    if km[i] > 最多:
        最多 = km[i]
        第几天 = i + 1
    if km[i] == 0:
        休息天数 += 1
    print(f"第{i + 1}圈 i={i} km[i]={km[i]} → 最多={最多} 第几天={第几天} 休息天数={休息天数}")
