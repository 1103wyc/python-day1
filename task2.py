steps = [6200, 7800, 5100, 9300, 10400, 4300, 8800]
                  # 每天至少这么多步才算达标
目标=8000
count = 0                   # 计数器，先归零

for i in range(len(steps)):    # i 依次是 0 1 2 3 4 5 6
    if steps[i] >= 8000:       # 这一天达标了
        print(f"第 {i + 1} 天 {steps[i]} 步，达标")
        count +=1

print(f'达标{count}天 占{count/len(steps)*100:.0f}%')
# 达标 3 天，占 43%
# 提示：百分比 = 达标天数 / 总天数 * 100；f 字符串里写 {值:.0f} 表示保留整数。

